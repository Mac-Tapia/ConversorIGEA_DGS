"""002:RF-7; 050:RF-2: productores de muestras, inyectados sin importar trabajadores."""
from __future__ import annotations
from collections.abc import Mapping, Sequence
from typing import Any, Protocol


class ProductoresMuestras(Protocol):
    """La composición decide las implementaciones; la aplicación conserva las puertas."""

    def lenguaje(self, instantanea: Mapping, referencias: Mapping, familias: Sequence[str]) -> list[Any]: ...
    def pinn(self, instantanea: Mapping, referencias: Mapping) -> list[Any]: ...
    def gru(self, instantanea: Mapping, referencias: Mapping, parametros: Mapping) -> list[Any]: ...
    def qlora(self, instantanea: Mapping, referencias: Mapping) -> list[Any]: ...
    def evolutivos(self, instantanea: Mapping) -> list[Any]: ...
